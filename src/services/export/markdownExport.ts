import { Project, Page } from '../../types'

export function generateProjectMarkdown(project: Project): string {
  const lines: string[] = []

  lines.push(`# ${project.name}`)
  if (project.description) {
    lines.push(`> ${project.description}\n`)
  } else {
    lines.push('')
  }

  lines.push(`- **Total Pages:** ${project.pages.length}`)
  lines.push(`- **Total Sections:** ${project.sections.length}`)
  lines.push(`- **Global Reusable Sections:** ${project.globalSections.length}`)
  lines.push(`- **Last Updated:** ${new Date(project.updatedAt).toLocaleDateString()}\n`)

  lines.push('## Sitemap Hierarchy\n')

  // Build tree
  const pageMap = new Map<string, Page>()
  const childrenMap = new Map<string | null, Page[]>()

  project.pages.forEach((p) => {
    pageMap.set(p.id, p)
    const list = childrenMap.get(p.parentId) || []
    list.push(p)
    childrenMap.set(p.parentId, list)
  })

  function printHierarchy(parentId: string | null, depth = 0) {
    const children = childrenMap.get(parentId) || []
    children.forEach((child) => {
      const indent = '  '.repeat(depth)
      lines.push(`${indent}- **[${child.name}](${child.slug})** \`[${child.type}]\`${child.description ? ` — ${child.description}` : ''}`)
      printHierarchy(child.id, depth + 1)
    })
  }

  printHierarchy(null, 0)
  lines.push('\n---\n')

  lines.push('## Detailed Page Specifications\n')

  project.pages.forEach((page, index) => {
    lines.push(`### ${index + 1}. ${page.name}`)
    lines.push(`- **URL Slug:** \`${page.slug}\``)
    lines.push(`- **Page Type:** \`${page.type}\``)
    lines.push(`- **Status:** \`${page.visibility}\``)
    if (page.parentId && pageMap.has(page.parentId)) {
      lines.push(`- **Parent Page:** ${pageMap.get(page.parentId)!.name} (\`${pageMap.get(page.parentId)!.slug}\`)`)
    }
    if (page.description) {
      lines.push(`- **Description:** ${page.description}`)
    }
    if (page.notes) {
      lines.push(`- **Internal Notes:** ${page.notes}`)
    }

    const pageSections = project.sections.filter((s) => s.pageId === page.id)
    if (pageSections.length > 0) {
      lines.push('\n#### Page Sections:')
      pageSections
        .sort((a, b) => a.position - b.position)
        .forEach((sec, sIdx) => {
          const globalTag = sec.isGlobal ? ' *(Global Synced)*' : ''
          lines.push(`  ${sIdx + 1}. **${sec.name}** (\`${sec.type}\`)${globalTag}`)
          if (sec.description) {
            lines.push(`     - ${sec.description}`)
          }
          if (sec.notes) {
            lines.push(`     - *Note: ${sec.notes}*`)
          }
        })
    } else {
      lines.push('\n*No sections added yet.*')
    }

    lines.push('\n')
  })

  if (project.globalSections.length > 0) {
    lines.push('---\n## Global Reusable Components\n')
    project.globalSections.forEach((gsec) => {
      lines.push(`### 🌐 ${gsec.name} (\`${gsec.type}\`)`)
      lines.push(`- ${gsec.description}`)
      if (gsec.notes) {
        lines.push(`- *Guideline: ${gsec.notes}*`)
      }
      lines.push('')
    })
  }

  lines.push('---\n*Generated by OpenSitemap — The Open Source AI Sitemap & Wireframe Builder*')

  return lines.join('\n')
}

export function downloadProjectMarkdown(project: Project): void {
  const content = generateProjectMarkdown(project)
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  const safeName = project.name.toLowerCase().replace(/[^a-z0-9_-]/g, '_')
  a.download = `${safeName || 'sitemap'}_spec.md`
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}
